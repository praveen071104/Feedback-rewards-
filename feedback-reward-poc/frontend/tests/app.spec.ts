function clearTestDatabase() {
  const database = process.env.FEEDBACK_E2E_DATABASE
  if (!database || !/^feedback_reward_e2e_[0-9a-f]{32}$/.test(database)) throw new Error('Refusing to clear a non-test database')
  execFileSync(python, ['-c', 'import sys; from pymongo import MongoClient; client = MongoClient("mongodb://127.0.0.1:27017/", serverSelectionTimeoutMS=3000); client.drop_database(sys.argv[1]); client.close()', database])
}

