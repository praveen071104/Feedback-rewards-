test('customer journey retries lost responses without duplicate cases or clearing input', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Customer Name').fill('Phone Customer')
  await page.getByLabel('Phone number', { exact: true }).fill('abc')
  await page.getByLabel('Feedback (required)', { exact: true }).fill('The fitting room lock broke during my visit yesterday.')
  await page.getByRole('radio', { name: '1 star: Very Poor' }).check()
  await page.getByRole('button', { name: 'Submit Feedback', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('7 to 15 digits')
  await page.getByLabel('Phone number', { exact: true }).fill('+44 7700 900123')
  const ids: string[] = []
  let release!: () => void
  const hold = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/customer-feedback', async route => {
    ids.push(route.request().postDataJSON().submission_id)
    if (ids.length === 1) await hold
    const response = await route.fetch()
    if (ids.length === 1) await route.fulfill({ status: 503, json: { detail: 'Confirmation lost. Please retry.' } })
    else await route.fulfill({ response })
  })
  await page.getByRole('button', { name: 'Submit Feedback', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Submitting feedback...' })).toBeDisabled()
  await expect(page.getByLabel('Customer Name')).toBeDisabled()
  release()
  await expect(page.getByRole('alert')).toContainText('Please retry')
  await expect(page.getByLabel('Customer Name')).toHaveValue('Phone Customer')
  await page.getByRole('button', { name: 'Submit Feedback', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Feedback submitted successfully.')
  expect(ids).toHaveLength(2)
  expect(ids[0]).toBe(ids[1])
  const result = await (await page.request.get('/api/colleague/feedback-cases')).json()
  expect(result.total).toBe(1)
  const detail = await (await page.request.get(`/api/colleague/feedback-cases/${ids[0]}`)).json()
  expect(detail.customer.sparks_id).toBeNull()
  expect(detail.customer.email).toBeNull()
})

